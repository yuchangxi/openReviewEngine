"""Deterministic file selection (after Alibaba OCR): skip files no reviewer should read.

Skipped files stay in the full diff list, so later stages (impact map) can still see
renames and deletions; selection only decides what specialists review line by line.
"""

from __future__ import annotations

import re
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from enum import StrEnum
from fnmatch import fnmatch
from pathlib import PurePosixPath

from deep_review.diff.parser import FileDiff

LOCK_FILES = frozenset(
    {
        "package-lock.json",
        "npm-shrinkwrap.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "bun.lockb",
        "poetry.lock",
        "Pipfile.lock",
        "uv.lock",
        "pdm.lock",
        "Cargo.lock",
        "go.sum",
        "composer.lock",
        "Gemfile.lock",
        "Podfile.lock",
        "pubspec.lock",
        "mix.lock",
        "packages.lock.json",
        "gradle.lockfile",
        "flake.lock",
    }
)
VENDOR_DIRS = frozenset(
    {
        "vendor",
        "third_party",
        "third-party",
        "thirdparty",
        "node_modules",
        "bower_components",
        "Pods",
        "Carthage",
        ".yarn",
    }
)
# Name rules only for unambiguous generator output; everything else relies on header markers.
GENERATED_DIRS = frozenset({"__generated__"})
GENERATED_GLOBS = (
    "*.pb.go",
    "*.pb.gw.go",
    "*_pb2.py",
    "*_pb2.pyi",
    "*_pb2_grpc.py",
    "*.pb.cc",
    "*.pb.h",
    "*.g.dart",
    "*.freezed.dart",
    "*.generated.*",
    "*_generated.*",
    "zz_generated*",
    "*.designer.cs",
)
MINIFIED_GLOBS = ("*.min.js", "*.min.mjs", "*.min.css", "*.js.map", "*.css.map", "*.bundle.js")
GENERATED_MARKER = re.compile(
    r"Code generated .* DO NOT EDIT|@generated\b|<auto-generated|"
    r"(?i:this file (?:is|was) (?:automatically|auto-)generated)|(?i:do not edit.{0,20}generated)"
)
LFS_POINTER_PREFIX = "version https://git-lfs.github.com/spec/"
_HEADER_LINES = 5


class SkipReason(StrEnum):
    BINARY = "binary"
    LFS_POINTER = "lfs_pointer"
    LOCK_FILE = "lock_file"
    VENDORED = "vendored"
    GENERATED = "generated"
    MINIFIED = "minified"
    TOO_LARGE = "too_large"
    NO_TEXT_CHANGE = "no_text_change"


@dataclass(slots=True)
class FileSelection:
    selected: list[FileDiff] = field(default_factory=list)
    skipped: list[tuple[FileDiff, SkipReason]] = field(default_factory=list)


def _header_text(fd: FileDiff, read_head: Callable[[str], str | None] | None) -> str:
    if read_head is not None and fd.new_path is not None:
        content = read_head(fd.new_path)
        if content is not None:
            return "\n".join(content.split("\n", _HEADER_LINES)[:_HEADER_LINES])
    # Fall back to the diff itself when the file's first lines are in a hunk.
    for h in fd.hunks:
        if h.new_start == 1:
            return "\n".join(ln.text for ln in h.lines[:_HEADER_LINES] if ln.kind != "del")
    return ""


def classify(
    fd: FileDiff,
    *,
    read_head: Callable[[str], str | None] | None = None,
    max_changed_lines: int = 3_000,
    max_line_length: int = 1_000,
) -> SkipReason | None:
    """Return why `fd` should be skipped, or None to review it."""
    if fd.is_binary:
        return SkipReason.BINARY
    path = PurePosixPath(fd.path)
    name, dirs = path.name, path.parts[:-1]
    if name in LOCK_FILES:
        return SkipReason.LOCK_FILE
    if any(d in VENDOR_DIRS for d in dirs):
        return SkipReason.VENDORED
    if any(fnmatch(name, g) for g in MINIFIED_GLOBS):
        return SkipReason.MINIFIED
    if any(d in GENERATED_DIRS for d in dirs) or any(fnmatch(name, g) for g in GENERATED_GLOBS):
        return SkipReason.GENERATED
    if not fd.hunks:
        return SkipReason.NO_TEXT_CHANGE  # pure rename / mode change / empty file
    added = [ln.text for h in fd.hunks for ln in h.lines if ln.kind == "add"]
    if added and added[0].startswith(LFS_POINTER_PREFIX):
        return SkipReason.LFS_POINTER
    if any(len(t) > max_line_length for t in added):
        return SkipReason.MINIFIED
    if fd.status != "deleted" and GENERATED_MARKER.search(_header_text(fd, read_head)):
        return SkipReason.GENERATED
    if fd.additions + fd.deletions > max_changed_lines:
        return SkipReason.TOO_LARGE
    return None


def select_files(
    diffs: Iterable[FileDiff],
    *,
    read_head: Callable[[str], str | None] | None = None,
    max_changed_lines: int = 3_000,
    max_line_length: int = 1_000,
) -> FileSelection:
    sel = FileSelection()
    for fd in diffs:
        reason = classify(
            fd,
            read_head=read_head,
            max_changed_lines=max_changed_lines,
            max_line_length=max_line_length,
        )
        if reason is None:
            sel.selected.append(fd)
        else:
            sel.skipped.append((fd, reason))
    return sel

from __future__ import annotations

import pytest

from deep_review.diff import SkipReason, parse_unified_diff, select_files
from deep_review.diff.parser import DiffLine, FileDiff, Hunk


def _fd(path: str, added: list[str], *, start: int = 1, binary: bool = False) -> FileDiff:
    lines = [DiffLine("add", None, start + i, t) for i, t in enumerate(added)]
    hunks = [Hunk(0, 0, start, len(added), "", lines)] if added else []
    return FileDiff(old_path=path, new_path=path, is_binary=binary, hunks=hunks)


@pytest.mark.parametrize(
    ("path", "added", "reason"),
    [
        ("src/app.py", ["x = 1"], None),
        ("assets/logo.png", [], SkipReason.BINARY),
        ("frontend/package-lock.json", ["{}"], SkipReason.LOCK_FILE),
        ("go.sum", ["x"], SkipReason.LOCK_FILE),
        ("vendor/github.com/x/y.go", ["package y"], SkipReason.VENDORED),
        ("web/node_modules/a/index.js", ["x"], SkipReason.VENDORED),
        ("api/v1/service.pb.go", ["package v1"], SkipReason.GENERATED),
        ("proto/msg_pb2.py", ["x"], SkipReason.GENERATED),
        ("static/app.min.js", ["x"], SkipReason.MINIFIED),
        ("static/app.js", ["x" * 5000], SkipReason.MINIFIED),
        (
            "gen/client.go",
            ["// Code generated by protoc-gen-go. DO NOT EDIT.", "package gen"],
            SkipReason.GENERATED,
        ),
        ("models/user.py", ["# @generated by tool", "x = 1"], SkipReason.GENERATED),
        (
            "data/big.bin",
            ["version https://git-lfs.github.com/spec/v1", "oid sha256:ab"],
            SkipReason.LFS_POINTER,
        ),
        # Hand-written code that merely mentions these words must be kept.
        ("src/mock_client.go", ["package src"], None),
        ("src/entity.java", ["@GeneratedValue", "private Long id;"], None),
        ("src/generated/handwritten.py", ["x = 1"], None),
    ],
)
def test_classification(path: str, added: list[str], reason: SkipReason | None) -> None:
    fd = _fd(path, added, binary=reason is SkipReason.BINARY)
    sel = select_files([fd])
    if reason is None:
        assert sel.selected == [fd] and not sel.skipped
    else:
        assert sel.skipped == [(fd, reason)]


def test_generated_marker_read_from_head_when_header_not_in_diff() -> None:
    fd = _fd("pkg/types.go", ["func X() {}"], start=40)
    heads = {"pkg/types.go": "// Code generated by stringer. DO NOT EDIT.\npackage pkg\n"}
    sel = select_files([fd], read_head=heads.get)
    assert sel.skipped == [(fd, SkipReason.GENERATED)]


def test_too_large_and_pure_rename() -> None:
    big = _fd("src/huge.py", ["x"] * 50)
    rename = parse_unified_diff(
        "diff --git a/a.py b/b.py\nsimilarity index 100%\nrename from a.py\nrename to b.py\n"
    )[0]
    sel = select_files([big, rename], max_changed_lines=10)
    assert sel.skipped == [(big, SkipReason.TOO_LARGE), (rename, SkipReason.NO_TEXT_CHANGE)]
